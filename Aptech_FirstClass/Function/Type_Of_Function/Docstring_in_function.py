# docstring describes what the function does.
# it inproves code readability 
# useful for help function and documentation generation tools.
# clean practice for a very good code

# example of docstring in function -----------------

def computation (a,b):
    # so this is a docstring that describes what the function does. it is enclosed in triple quotes and is placed immediately after the function definition.
    """
    This function takes two numbers as input and returns their sum, difference, product, and quotient.
    """
    return a + b
print(computation(5, 10)) # output: 15
    