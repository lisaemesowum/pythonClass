# list is a collection of array which is changeable

# Example
fruit = ["apple", "banana", "orange",10,20,19]
print(fruit)

# it uses indexing 
print(fruit[2:6])

# updating the values
fruit[1] = "lisa"
print(fruit)

# append - means adding a value at the end of the list
fruit.append(10)

# reversed - to reverse the values
fruit.reverse()
print(fruit)
