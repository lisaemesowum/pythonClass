# comparison operators 
# it is used to compare two operands. returns either True or False.

# List of comparison operators

# 1: Greater than       (>)
# -------- example --------
x = 10
y = 20
sum = x > y
print(sum)

# 2: Less than          (<)
# -------- example --------
x = 10
y = 20
sum = x < y
print(sum)

# 3: Equal to     (==) RETURNS TRUE IF THE LEFT OPERAND IS EQUAL TO THE RIGHT OPERAND.
# -------- example --------
x = 10
y = 20
sum = x == y
print(sum)

# 4: Less than or Equal to (<=) RETURN TRUE IF THE LEFT OPRAND IS LESS THEN OR EQUAL TO THE RIGHT OPERAND
# -------- example --------
x = 10
y = 20
sum = x <= y
print(sum)

# 5: Greater than or Equal to (>=) RETURN TRUE IF THE LEFT OPRAND IS GREATER THEN OR EQUAL TO THE RIGHT OPERAND
# -------- example --------
x = 10
y = 20
sum = x >= y
print(sum)

# 4: Not Equal to (!=) RETURNS TRUE IF THE LEFT OPERAND IS NOT EQUAL TO THE RIGHT OPERAND.
# -------- example --------
x = 10
y = 20
sum = x != y
print(sum)

