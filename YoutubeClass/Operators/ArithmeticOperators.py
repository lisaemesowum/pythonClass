# list of arithmetic operators

# 1: Addition               (+) 
#--------- Example ------------
x = 10
y = 20
sum = x + y
print(sum)

# 2: Subtraction            (-)
#--------- Example ------------
x = 10
y = 20
sum = x - y
print(sum)

# 3: division               (/)
#--------- Example ------------
x = 10
y = 20
sum = x / y
print(sum)

# 4: Multiplication          (*)
#--------- Example ------------
x = 10
y= 20
sum = x * y
print(sum)

# 5: Floor Division          (//) ALWAYS GIVES INTEGER
#--------- Example ------------
x = 10
y= 20
sum = x // y
print(sum)

# 6: Modulus                (%) PERFORMS DIVISION, BUT IT RETURNS THE REMAINDER AS A RESULT
#--------- Example ------------
x = 10
y= 20
sum = x % y
print(sum)

# 7: Power                  (**) CALCULATES THE FIRST OPERAND RAISED TO THE POWER SECOND OPERAND
#--------- Example ------------
x = 10
y= 2
sum = x ** y
print(sum)